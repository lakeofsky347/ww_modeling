def boot_ids(preset, id_to_mod):
    """First-screen chunk ids: index, engine, worker, then the default team's modules/records (ids sorted)."""
    team = preset['config']['team']
    mods = sorted({id_to_mod[m['id']] for m in team})
    ress = sorted(m['id'] for m in team)
    wpns = sorted({m['weapon']['id'] for m in team if (m.get('weapon') or {}).get('id')})
    echos = sorted({e['echoId'] for m in team for e in (m.get('echoes') or []) if e.get('echoId')})
    ids = ['index', 'engine', 'worker']
    ids += [f'mod:{i}' for i in mods]
    ids += [f'res:{i}' for i in ress]
    ids += [f'wpn:{i}' for i in wpns]
    ids += [f'echo:{i}' for i in echos]
    return ids


def file_hash(path):
    return sha(open(path, 'rb').read())


def copy_icons(src_dir, dst_dir):
    if os.path.isdir(dst_dir):
        shutil.rmtree(dst_dir)
    os.makedirs(dst_dir, exist_ok=True)
    hashes = {}
    if not os.path.isdir(src_dir):
        return hashes
    for name in sorted(os.listdir(src_dir)):
        sp = os.path.join(src_dir, name)
        if not os.path.isfile(sp):
            continue
        shutil.copyfile(sp, os.path.join(dst_dir, name))
        hashes[os.path.splitext(name)[0]] = sha(open(sp, 'rb').read())
    return hashes


def attach_skill_icons(resonators, skill_hashes):
    for r in resonators:
        for sk in r.get('skills') or []:
            sid = str(sk.get('id'))
            if sid in skill_hashes:
                sk['skillIcon'] = f'assets/skills/{sid}.webp?v={skill_hashes[sid]}'


def join_scripts(parts):
    out = []
    for i, text in enumerate(parts):
        if not text.endswith('\n'):
            text += '\n'
        out.append(text)
        if i != len(parts) - 1:
            out.append('\n')
    return ''.join(out)


def build_html(skel, hashes, page_cfg, scripts_js):
    meta = re.search(r'<meta charset="utf-8">.*\n<title>.*</title>\n', skel)
    if not meta:
        sys.exit('[ww] skeleton is missing the charset/title block')
    body = skel.split('<body>', 1)[1].split('<script', 1)[0]
    ver = ENGINE_VERSION
    ev = (
        f'<script data-sim="engine-version">window.__SIM_ENGINE_VERSION__="{ver}";'
        f'window.__simAssets=window.__simAssets||{{game:"ww",engineVersion:"{ver}"}};</script>\n'
    )
    migrate = open(os.path.join(PIPE, 'shared', 'migrate_ww.js'), encoding='utf-8').read()
    nav = json.dumps(SIM_NAV, ensure_ascii=False, separators=(',', ':'))
    theme_v = json.dumps({n: hashes['theme'][n] for n in LAZY_JS}, ensure_ascii=False, separators=(',', ':'))
    lines = [ev, f'<script data-sim="migrate-config">{migrate}</script>\n', '\n', meta.group(0)]
    lines.append(f'<link rel="stylesheet" href="assets/theme/common.css?v={hashes["theme"]["common.css"]}">\n')
    lines.append(f'<link rel="stylesheet" href="assets/theme/ww.css?v={hashes["theme"]["ww.css"]}">\n')
    lines.append(f'<link rel="icon" type="image/svg+xml" href="assets/theme/favicon-ww.svg?v={hashes["theme"]["favicon-ww.svg"]}">\n')
    for href in hashes['preloads']:
        lines.append(f'<link rel="preload" as="fetch" crossorigin="anonymous" href="{href}">\n')
    lines.append(f'<link rel="stylesheet" href="assets/theme/interact.css?v={hashes["theme"]["interact.css"]}">\n')
    lines.append(f'<script>window.__SIM_NAV={nav};</script>\n')
    for name, defer in HEAD_JS:
        attr = ' defer' if defer else ''
        lines.append(f'<script{attr} src="assets/theme/{name}?v={hashes["theme"][name]}"></script>\n')
        if name == 'gamenav.js':
            lines.append(f'<script>window.__themeV={theme_v};</script>\n')
    head = ''.join(lines)
    cfg = json.dumps(page_cfg, ensure_ascii=False).replace('</', '<\\/')
    tail = (
        f'<script src="assets/theme/bg-webgl.js?v={hashes["theme"]["bg-webgl.js"]}"></script>\n'
        f'<script src="assets/ww-engine.js?v={hashes["engine"]}"></script>\n'
        f'<script>window.__WW_PAGE__ = {cfg};</script>\n'
        '<script>\n' + scripts_js + '</script>\n'
    )
    return '<!doctype html>\n<html lang="zh-CN" data-theme="ww">\n<head>\n' + head + '</head>\n<body>' + body + tail + '</body>\n</html>\n'


def chunk_entry(cid, kind, path, blob, boot, owner=None):
    ent = {'id': cid, 'kind': kind, 'path': path, 'v': sha(blob), 'size': len(blob), 'gzip': gzip_len(blob), 'boot': cid in boot}
    if owner:
        ent['owner'] = owner
    return ent


def build(dist, data_path, theme_script, skel_path=None, layout='per-game', theme_apply=None, avatar_fn=None):
    """Write the self-contained dist/ww package. v3.5 is always per-game (page-relative assets/ and data/)."""
    if layout != 'per-game':
        print('[ww] v3.5 package is self-contained under dist/ww/; ignoring layout=%s' % layout, file=sys.stderr)
    page_dir = os.path.join(dist, 'ww')
    skel_path = skel_path or os.path.join(ROOT, 'frontend', 'ww', 'index.html')
    engine_dir = os.path.join(WW, 'engine')
    data = json.load(open(data_path, encoding='utf-8'))
    meta = data['meta']
    if meta.get('version') != EXPECT_VERSION:
        print(f'[ww] warning: data version {meta.get("version")} != {EXPECT_VERSION}', file=sys.stderr)

    os.makedirs(os.path.join(page_dir, 'assets'), exist_ok=True)
    data_dir = os.path.join(page_dir, 'data')
    if os.path.isdir(data_dir):
        shutil.rmtree(data_dir)
    os.makedirs(data_dir, exist_ok=True)

    if avatar_fn:
        avatar_fn('ww', data['resonators'], page_dir)
    else:
        for r in data['resonators']:
            r.setdefault('avatar', None)
    for r in data['resonators']:
        rel = r.get('avatar')
        if not rel:
            continue
        fp = os.path.join(page_dir, rel.split('?', 1)[0])
        if os.path.isfile(fp):
            r['avatar'] = rel.split('?', 1)[0] + '?v=' + sha(open(fp, 'rb').read())

    skill_hashes = copy_icons(os.path.join(ROOT, 'assets-src', 'icons', 'ww', 'skills'), os.path.join(page_dir, 'assets', 'skills'))
    element_hashes = copy_icons(os.path.join(ROOT, 'assets-src', 'icons', 'ww', 'elements'), os.path.join(page_dir, 'assets', 'elements'))
    attach_skill_icons(data['resonators'], skill_hashes)
    element_icons = {name: f'assets/elements/{name}.webp?v={element_hashes[name]}' for name in sorted(element_hashes)}

    data['runtime'] = runtime(os.path.join(WW, 'validation', 'substat_tiers.json'), os.path.join(WW, 'validation', 'action_frames.json'))

    bundle = engine_bundle(engine_dir)
    bundle_b = bundle.encode('utf-8')
    worker_b = read_text(os.path.join(HERE, 'worker.js')).encode('utf-8')
    open(os.path.join(page_dir, 'assets', 'ww-engine.js'), 'wb').write(bundle_b)
    open(os.path.join(page_dir, 'assets', 'ww-worker.js'), 'wb').write(worker_b)

    modules = module_sources(engine_dir)
    mod_blobs = {}
    id_to_mod = {}
    modules_map = {}
    for filename, file_id, ids, text in modules:
        blob = module_chunk(filename, file_id, text).encode('utf-8')
        mod_blobs[file_id] = blob
        open(os.path.join(data_dir, f'ww-m{file_id}-engine.js'), 'wb').write(blob)
        for i in [file_id] + [x for x in ids if x != file_id]:
            if str(i) not in modules_map:
                modules_map[str(i)] = f'mod:{file_id}'
                id_to_mod[i] = file_id

    version = meta['version']
    record_blobs = {}  # cid -> (kind, path, blob, owner)
    for r in data['resonators']:
        cid = f'res:{r["id"]}'
        blob = dump({'chunk': cid, 'game': 'ww', 'dataVersion': version, 'kind': 'resonator', 'record': r})
        record_blobs[cid] = ('char', f'data/ww-r{r["id"]}.json', blob, {'type': 'resonator', 'ids': [r['id']]})
    for w in data['weapons']:
        cid = f'wpn:{w["id"]}'
        blob = dump({'chunk': cid, 'game': 'ww', 'dataVersion': version, 'kind': 'weapon', 'record': w})
        record_blobs[cid] = ('weapon', f'data/ww-w{w["id"]}.json', blob, {'type': 'weapon', 'ids': [w['id']]})
    for e in data['echoes']:
        cid = f'echo:{e["id"]}'
        blob = dump({'chunk': cid, 'game': 'ww', 'dataVersion': version, 'kind': 'echo', 'record': e})
        record_blobs[cid] = ('echo', f'data/ww-e{e["id"]}.json', blob, {'type': 'echo', 'ids': [e['id']]})
    for cid, (_kind, rel, blob, _owner) in record_blobs.items():
        open(os.path.join(page_dir, rel), 'wb').write(blob)

    index = {}
    for key in ('meta', 'resonators', 'weapons', 'echoes', 'echoMainStats', 'echoMainStatsNote',
                'echoSubStats', 'echoSubStatsNote', 'echoCost', 'sonatas', 'enemies', 'enemyGrowth', 'anomalies'):
        if key == 'resonators':
            index[key] = [{k: r[k] for k in RES_SLIM} for r in data['resonators']]
        elif key == 'weapons':
            index[key] = [{k: w[k] for k in WPN_SLIM} for w in data['weapons']]
        elif key == 'echoes':
            index[key] = [{k: e[k] for k in ECHO_SLIM} for e in data['echoes']]
        else:
            index[key] = data[key]
    index['elementIcons'] = element_icons
    index['runtime'] = data['runtime']
    index_b = dump(index)
    open(os.path.join(data_dir, 'ww.json'), 'wb').write(index_b)

    presets_list = page_presets(engine_dir)
    boot = boot_ids(presets_list[0], id_to_mod)
    boot_set = set(boot)

    chunks = []
    blobs_by_id = {
        'index': index_b,
        'engine': bundle_b,
        'worker': worker_b,
    }
    chunks.append(chunk_entry('index', 'index', 'data/ww.json', index_b, boot_set))
    chunks.append(chunk_entry('engine', 'engine', 'assets/ww-engine.js', bundle_b, boot_set))
    chunks.append(chunk_entry('worker', 'worker', 'assets/ww-worker.js', worker_b, boot_set))
    for filename, file_id, ids, text in modules:
        cid = f'mod:{file_id}'
        blob = mod_blobs[file_id]
        blobs_by_id[cid] = blob
        chunks.append(chunk_entry(cid, 'module', f'data/ww-m{file_id}-engine.js', blob, boot_set,
                                  {'type': 'resonator', 'ids': ids}))
    for cid in sorted((c for c in record_blobs if c.startswith('res:')), key=lambda s: int(s.split(':')[1])):
        kind, rel, blob, owner = record_blobs[cid]
        blobs_by_id[cid] = blob
        chunks.append(chunk_entry(cid, kind, rel, blob, boot_set, owner))
    for cid in sorted((c for c in record_blobs if c.startswith('wpn:')), key=lambda s: int(s.split(':')[1])):
        kind, rel, blob, owner = record_blobs[cid]
        blobs_by_id[cid] = blob
        chunks.append(chunk_entry(cid, kind, rel, blob, boot_set, owner))
    for cid in sorted((c for c in record_blobs if c.startswith('echo:')), key=lambda s: int(s.split(':')[1])):
        kind, rel, blob, owner = record_blobs[cid]
        blobs_by_id[cid] = blob
        chunks.append(chunk_entry(cid, kind, rel, blob, boot_set, owner))

    manifest = {
        'schema': 'sim-chunks-1', 'game': 'ww', 'dataVersion': version, 'generated': CHUNK_GENERATED,
        'hash': 'sha256-12', 'split': True, 'boot': boot, 'chunks': chunks,
        'modules': sorted(int(k) for k in modules_map),
        'totals': {
            'count': len(chunks),
            'size': sum(c['size'] for c in chunks),
            'gzip': sum(c['gzip'] for c in chunks),
            'bootSize': sum(c['size'] for c in chunks if c['boot']),
            'bootGzip': sum(c['gzip'] for c in chunks if c['boot']),
        },
    }
    manifest_b = dump(manifest)
    open(os.path.join(data_dir, 'chunks.json'), 'wb').write(manifest_b)
    manifest_v = sha(manifest_b)

    by_id = {c['id']: c for c in chunks}
    page_boot = []
    preloads = [f'data/ww.json?v={by_id["index"]["v"]}', f'data/chunks.json?v={manifest_v}']
    for cid in boot:
        if cid in ('engine', 'worker'):
            continue
        c = by_id[cid]
        page_boot.append({'id': c['id'], 'kind': c['kind'], 'url': f'{c["path"]}?v={c["v"]}', 'size': c['size']})
        if cid != 'index':
            preloads.append(f'{c["path"]}?v={c["v"]}')

    page_cfg = {
        'dataUrl': f'data/ww.json?v={by_id["index"]["v"]}',
        'engineUrl': f'assets/ww-engine.js?v={by_id["engine"]["v"]}',
        'workerUrl': f'assets/ww-worker.js?v={by_id["worker"]["v"]}',
        'version': version,
        'commit': meta['source_commit'],
        'storageKey': STORAGE_KEY,
        'presets': presets_list,
        'engineVersion': ENGINE_VERSION,
        'chunksUrl': f'data/chunks.json?v={manifest_v}',
        'chunkBase': '',
        'boot': page_boot,
        'modules': modules_map,
    }

    theme_dir = os.path.join(ROOT, 'frontend', 'theme')
    theme_hashes = {}
    for name in sorted(os.listdir(theme_dir)):
        fp = os.path.join(theme_dir, name)
        if os.path.isfile(fp):
            theme_hashes[name] = file_hash(fp)
    scripts_js = join_scripts([
        open(os.path.join(PIPE, 'shared', 'sim_chunks.js'), encoding='utf-8').read(),
        open(os.path.join(PIPE, 'shared', 'sim_bridge.js'), encoding='utf-8').read(),
        open(os.path.join(HERE, 'app.js'), encoding='utf-8').read(),
    ])
    html = build_html(open(skel_path, encoding='utf-8').read(), {
        'theme': theme_hashes, 'preloads': preloads, 'engine': by_id['engine']['v'],
    }, page_cfg, scripts_js)
    final = os.path.join(page_dir, 'index.html')
    with tempfile.NamedTemporaryFile('w', suffix='.html', delete=False, encoding='utf-8') as t:
        t.write(html)
    if theme_apply:
        theme_apply('ww', t.name, final)
    else:
        subprocess.check_call([sys.executable, theme_script, 'ww', t.name, final, '--prefix', 'assets/theme/'])
        td = os.path.join(page_dir, 'assets', 'theme')
        os.makedirs(td, exist_ok=True)
        for name in os.listdir(theme_dir):
            sp = os.path.join(theme_dir, name)
            if os.path.isfile(sp):
                shutil.copyfile(sp, os.path.join(td, name))
    os.unlink(t.name)
    print(f'ww: {final} ({os.path.getsize(final) // 1024} KiB html) + ww-engine.js ({len(bundle_b) // 1024} KiB, core) '
          f'+ {len(modules)} module chunks + data/ww.json ({len(index_b) // 1024} KiB) '
          f'+ {len(record_blobs)} record chunks  version={version} engine={ENGINE_VERSION}')
    return final


