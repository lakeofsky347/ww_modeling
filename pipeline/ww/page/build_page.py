def sha(b):
    return hashlib.sha256(b).hexdigest()[:12]


def dump(obj):
    return json.dumps(obj, ensure_ascii=False, separators=(',', ':')).encode('utf-8')


def gzip_len(b):
    return len(gzip.compress(b, compresslevel=9))


def read_text(path):
    text = open(path, encoding='utf-8').read()
    if not text.endswith('\n'):
        text += '\n'
    return text


def engine_bundle(engine_dir):
    """Core bundle only. Character modules are separate chunks (v3.3+)."""
    chars = os.path.join(engine_dir, 'chars')
    paths = {
        'ww_engine.js': os.path.join(engine_dir, 'ww_engine.js'),
        'chars/_common.js': os.path.join(chars, '_common.js'),
        'chars/0_wb_lib.js': os.path.join(chars, '0_wb_lib.js'),
    }
    blocks = []
    for i, name in enumerate(CORE_PARTS):
        block = f'/* ==== {name} ==== */\n' + read_text(paths[name])
        if i != len(CORE_PARTS) - 1:
            block += '\n'
        blocks.append(block)
    return ENGINE_HEADER + ''.join(blocks)


def registered_ids(text, file_id):
    ids = [int(x) for x in re.findall(r'registerChar\(\s*def\(\s*(\d+)\s*\)', text)]
    for m in re.finditer(r'registerChar\(\s*\{', text):
        m2 = re.search(r'\bid\s*:\s*(\d+)', text[m.end():m.end() + 400])
        if m2:
            ids.append(int(m2.group(1)))
    if file_id not in ids:
        ids.append(file_id)
    return ids


def module_sources(engine_dir):
    """(filename, file_id, sorted registered ids, source text) for real modules. Alias stubs are skipped."""
    chars = os.path.join(engine_dir, 'chars')
    out = []
    for f in os.listdir(chars):
        if not re.match(r'^\d+_.*\.js$', f) or f == '0_wb_lib.js' or '_alias_' in f:
            continue
        text = read_text(os.path.join(chars, f))
        if not re.search(r'registerChar\s*\(', text):
            continue
        file_id = int(f.split('_', 1)[0])
        out.append((f, file_id, sorted(set(registered_ids(text, file_id))), text))
    out.sort(key=lambda t: t[1])
    return out


def module_chunk(filename, file_id, text):
    return f'/* ==== chars/{filename} (chunk mod:{file_id}) ==== */\n' + text


