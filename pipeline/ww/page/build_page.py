#!/usr/bin/env python3
"""Build the Wuthering Waves page into dist/.

  python3 pipeline/ww/page/build_page.py [--data pipeline/out/ww.json] [--dist dist]
  (also run by pipeline/build_pages.py, which builds hsr + endfield + ww)

Writes:
  dist/assets/ww-engine.js   engine bundle = engine/ww_engine.js + chars/_common.js + every chars/<digits>_*.js
                             (globbed at build time: newly added character modules are picked up by a rebuild;
                             the page lists modules via WWEngine.listChars(), so no page change is needed)
  dist/assets/ww-worker.js   Web Worker running simulate/search off the main thread (importScripts the bundle)
  dist/data/ww.json          out/ww.json + key `runtime` {schema, substatTiers, actionFrames (trimmed), framesInfo}
  dist/ww/index.html         frontend/ww/index.html with the MOCK script removed, the engine <script>, the page
                             config and page/app.js inlined; then frontend/apply-theme.py ww (idempotent)
All URLs are relative (../assets, ../data) with ?v=<sha256[:12]> cache busters, so dist works under a sub-path.
"""
import argparse, glob, hashlib, shutil, json, os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
WW = os.path.dirname(HERE)
PIPE = os.path.dirname(WW)
ROOT = os.path.dirname(PIPE)
sys.path.insert(0, HERE)
from runtime_data import runtime  # noqa: E402

EXPECT_VERSION = '3.7.8'
STORAGE_KEY = 'ww-sim:config:v1'


def sha(b):
    return hashlib.sha256(b).hexdigest()[:12]


def engine_bundle(engine_dir):
    chars = os.path.join(engine_dir, 'chars')
    mods = sorted(f for f in os.listdir(chars) if re.match(r'^\d+_.*\.js$', f))
    parts = [('ww_engine.js', os.path.join(engine_dir, 'ww_engine.js')), ('chars/_common.js', os.path.join(chars, '_common.js'))]
    parts += [('chars/' + f, os.path.join(chars, f)) for f in mods]
    out = ['/* WWEngine bundle — generated by pipeline/ww/page/build_page.py; do not edit.\n * parts: ' +
           ', '.join(p for p, _ in parts) + ' */\n']
    for name, p in parts:
        out.append(f'\n/* ==== {name} ==== */\n' + open(p, encoding='utf-8').read().rstrip() + '\n')
    return ''.join(out), [m.split('_')[0] for m in mods]


def presets(ex_dir):
    chars_ex = os.path.join(os.path.dirname(ex_dir), 'chars', 'examples')

    def load(n):
        p = os.path.join(ex_dir, n + '.json')
        if not os.path.exists(p):
            p = os.path.join(chars_ex, n + '.json')
        d = json.load(open(p, encoding='utf-8'))
        d.pop('expect', None)
        return d
    tj = load('team_jinhsi')
    cl = load('changli_solo_search')
    # 长离/折枝/守岸人: 长离's build from changli_solo_search, supports and settings from team_jinhsi
    team_cl = json.loads(json.dumps(tj))
    team_cl['name'] = '长离/折枝/守岸人 25s 自动搜索'
    team_cl['team'][0] = cl['team'][0]
    out = []
    for name, cfg in [('今汐/折枝/守岸人 · 满协奏开局（默认）', tj),
                      ('今汐/折枝/守岸人 · 30s 冷启动', load('team_jinhsi_cold')),
                      ('长离/折枝/守岸人 · 满协奏开局', team_cl),
                      ('今汐 单人 · 手动循环', load('jinhsi_solo')),
                      ('长离 单人 · 自动搜索', cl),
                      ('折枝 单人 · 自动搜索', load('zhezhi_solo')),
                      ('守岸人 单人 · 自动搜索', load('shorekeeper_solo')),
                      # character-module teams (engine/chars/examples)
                      ('珂莱塔/折枝/守岸人 · 自动搜索', load('team_carlotta')),
                      ('菲比/守岸人 · 自动搜索（光噪由队友维持）', load('team_phoebe')),
                      ('卡提希娅/守岸人 · 自动搜索（风蚀效应）', load('team_cartethyia')),
                      ('今汐/心/守岸人 · 同奏 自动搜索', load('team_hsin_jinhsi')),
                      ('爱弥斯/长离/守岸人 · 聚爆 自动搜索', load('team_aemeath'))]:
        cfg = {k: v for k, v in cfg.items() if k != 'name'}
        out.append({'name': name, 'config': cfg})
    # module team presets (stream A/B): any chars/examples/*.json carrying "preset": "<页面名称>" is appended (file-name order)
    seen = {o['name'] for o in out}
    for p in sorted(glob.glob(os.path.join(chars_ex, '*.json'))):
        d = json.load(open(p, encoding='utf-8'))
        name = d.get('preset')
        if not name or name in seen:
            continue
        seen.add(name)
        d.pop('expect', None)
        out.append({'name': name, 'config': {k: v for k, v in d.items() if k not in ('name', 'preset', 'source')}})
    return out


def assemble(skel, engine_url, page_cfg, app_js):
    m = re.search(r'[ \t]*<!--[^>]*MOCK[^>]*-->\s*<script id="ww-mock">.*?</script>\s*', skel, re.S)
    if not m:
        m = re.search(r'[ \t]*<script id="ww-mock">.*?</script>\s*', skel, re.S)
    if not m:
        sys.exit('[ww] <script id="ww-mock"> not found in skeleton')
    html = skel[:m.start()] + skel[m.end():]
    if 'ww-mock' in html:
        sys.exit('[ww] mock script still present')
    cfg_js = json.dumps(page_cfg, ensure_ascii=False).replace('</', '<\\/')
    inject = (f'<script src="{engine_url}"></script>\n'
              f'<script>window.__WW_PAGE__ = {cfg_js};</script>\n'
              '<script>\n' + app_js.replace('</script', '<\\/script') + '</script>\n')
    i = html.rfind('</body>')
    if i < 0:
        sys.exit('[ww] </body> not found')
    return html[:i] + inject + html[i:]


def build(dist, data_path, theme_script, skel_path=None, layout='shared', theme_apply=None, avatar_fn=None):
    """layout 'shared': dist/ww/index.html + dist/assets/ww-*.js + dist/data/ww.json (../ URLs);
    'per-game': self-contained dist/ww/{index.html, assets/ww-*.js, assets/theme/*, data/ww.json} (assets/, data/ URLs)."""
    per_game = layout == 'per-game'
    root, rel = (os.path.join(dist, 'ww'), '') if per_game else (dist, '../')
    skel_path = skel_path or os.path.join(ROOT, 'frontend', 'ww', 'index.html')
    engine_dir = os.path.join(WW, 'engine')
    data = json.load(open(data_path, encoding='utf-8'))
    meta = data['meta']
    if meta.get('version') != EXPECT_VERSION:
        print(f'[ww] warning: data version {meta.get("version")} != {EXPECT_VERSION}', file=sys.stderr)
    # avatars (build_pages.attach_avatars): resonators[i].avatar = 'assets/avatars/<id>.webp' | None, files copied next to dist/ww/index.html
    if avatar_fn:
        avatar_fn('ww', data['resonators'], os.path.join(dist, 'ww'))
    else:
        for r in data['resonators']:
            r.setdefault('avatar', None)
    data['runtime'] = runtime(os.path.join(WW, 'validation', 'substat_tiers.json'), os.path.join(WW, 'validation', 'action_frames.json'))
    data_b = json.dumps(data, ensure_ascii=False, separators=(',', ':')).encode('utf-8')
    bundle, mods = engine_bundle(engine_dir)
    worker = open(os.path.join(HERE, 'worker.js'), encoding='utf-8').read()
    if per_game and os.path.realpath(os.path.join(root, 'assets')) == os.path.realpath(os.path.join(dist, 'assets')):
        raise SystemExit('[ww] per-game layout must not write engine files into <dist>/assets')
    os.makedirs(os.path.join(root, 'assets'), exist_ok=True)
    os.makedirs(os.path.join(root, 'data'), exist_ok=True)
    os.makedirs(os.path.join(dist, 'ww'), exist_ok=True)
    open(os.path.join(root, 'assets', 'ww-engine.js'), 'w', encoding='utf-8').write(bundle)
    open(os.path.join(root, 'assets', 'ww-worker.js'), 'w', encoding='utf-8').write(worker)
    open(os.path.join(root, 'data', 'ww.json'), 'wb').write(data_b)
    ev, wv, dv = sha(bundle.encode()), sha(worker.encode()), sha(data_b)
    page_cfg = {'dataUrl': f'{rel}data/ww.json?v={dv}', 'engineUrl': f'{rel}assets/ww-engine.js?v={ev}',
                'workerUrl': f'{rel}assets/ww-worker.js?v={wv}', 'version': meta['version'], 'commit': meta['source_commit'],
                'storageKey': STORAGE_KEY, 'presets': presets(os.path.join(engine_dir, 'examples'))}
    html = assemble(open(skel_path, encoding='utf-8').read(), page_cfg['engineUrl'], page_cfg,
                    open(os.path.join(HERE, 'app.js'), encoding='utf-8').read())
    final = os.path.join(dist, 'ww', 'index.html')
    with tempfile.NamedTemporaryFile('w', suffix='.html', delete=False, encoding='utf-8') as t:
        t.write(html)
    if theme_apply:   # build_pages.apply_theme (handles the per-game theme copy)
        theme_apply('ww', t.name, final)
    else:             # standalone: frontend/apply-theme.py (injects gamenav.js too)
        subprocess.check_call([sys.executable, theme_script, 'ww', t.name, final, '--prefix', rel + 'assets/theme/'])
    os.unlink(t.name)
    print(f'ww: {final} ({os.path.getsize(final) // 1024} KiB html) + assets/ww-engine.js ({len(bundle) // 1024} KiB, '
          f'modules {",".join(mods)}) + assets/ww-worker.js + data/ww.json ({len(data_b) // 1024} KiB) '
          f'version={meta["version"]} v={dv}')
    return final


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--data', default=os.path.join(PIPE, 'out', 'ww.json'))
    ap.add_argument('--dist', default=os.path.join(ROOT, 'dist'))
    ap.add_argument('--theme-script', default=os.path.join(ROOT, 'frontend', 'apply-theme.py'))
    ap.add_argument('--layout', choices=['shared', 'per-game'], default=None)
    a = ap.parse_args()
    lay = a.layout or ('shared' if os.path.basename(os.path.normpath(a.dist)) == 'dist' else 'per-game')
    build(a.dist, a.data, a.theme_script, layout=lay)
